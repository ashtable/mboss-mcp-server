const RUN_ROW: WorkflowStatusRow = {
  workflow_uuid: 'wf-1',
  name: 'groom_booking',
  status: 'SUCCESS',
  recovery_attempts: '1',
  created_at: '1756684800000',
  completed_at: '1756684802500',
};

const STEP_ROW: OperationOutputRow = {
  function_id: 1,
  function_name: 'findSlot',
  started_at_epoch_ms: '1756684800100',
  completed_at_epoch_ms: '1756684800400',
  error: null,
  child_workflow_id: null,
};

/** A database that answers with the rows it is given. */
function fakeDatabase(answers: unknown[][]): {
  open: () => Promise<Database>;
  asked: { text: string; values: unknown[] }[];
  closed: () => number;
} {
  const asked: { text: string; values: unknown[] }[] = [];
  let closes = 0;

  return {
    asked,
    closed: () => closes,
    open: () =>
      Promise.resolve({
        query: <R>(text: string, values: unknown[]) => {
          asked.push({ text, values });

          return Promise.resolve((answers[asked.length - 1] ?? []) as R[]);
        },
        close: () => {
          closes += 1;

          return Promise.resolve();
        },
      }),
  };
}

type DebugOutput = {
  runs: {
    workflowId: string;
    name: string;
    status: string;
    recoveryAttempts: number;
    startedAt: string;
    durationMs?: number;
    steps?: object[];
  }[];
};

describe('project_debug', () => {
  beforeEach(() => {
    fixture = makeFixtureProject();
  });

  it('answers with the recent runs', async () => {
    const db = fakeDatabase([[RUN_ROW]]);

    const seen = await output<DebugOutput>(call(makeProjectDebug(db.open)));

    expect(seen).toEqual({
      runs: [
        {
          workflowId: 'wf-1',
          name: 'groom_booking',
          status: 'SUCCESS',
          recoveryAttempts: 1,
          startedAt: '2025-09-01T00:00:00.000Z',
          durationMs: 2500,
        },
      ],
    });
    expect(db.asked).toHaveLength(1);
    expect(db.asked[0]?.values).toEqual([10]);
  });

  it('answers with a named run and its steps', async () => {
    const db = fakeDatabase([[RUN_ROW], [STEP_ROW]]);

    const seen = await output<DebugOutput>(
      call(makeProjectDebug(db.open), { runId: 'wf-1' }),
    );

    expect(db.asked.map((query) => query.values)).toEqual([['wf-1'], ['wf-1']]);
    expect(seen.runs[0]?.steps).toEqual([
      {
        functionID: 1,
        name: 'findSlot',
        startedAtEpochMs: 1756684800100,
        completedAtEpochMs: 1756684800400,
      },
    ]);
  });

  it('asks for no steps when the named run is gone', async () => {
    const db = fakeDatabase([[]]);

    const seen = await output<DebugOutput>(
      call(makeProjectDebug(db.open), { runId: 'gone' }),
    );

    expect(seen.runs).toEqual([]);
    expect(db.asked).toHaveLength(1);
  });

  it('closes the connection it opened', async () => {
    const db = fakeDatabase([[RUN_ROW]]);

    await call(makeProjectDebug(db.open));

    expect(db.closed()).toBe(1);
  });

  it('closes the connection when the read fails', async () => {
    const open = () =>
      Promise.resolve<Database>({
        query: () => Promise.reject(new Error('relation does not exist')),
        close: () => {
          closes += 1;

          return Promise.resolve();
        },
      });
    let closes = 0;

    await expect(call(makeProjectDebug(open))).rejects.toThrow(
      /relation does not exist/,
    );
    expect(closes).toBe(1);
  });

  it('refuses to ask for more than fifty runs', () => {
    const db = fakeDatabase([[RUN_ROW]]);

    // The cap is on the input, so the refusal
    // happens before anything opens a connection.
    expect(() => call(makeProjectDebug(db.open), { limit: 51 })).toThrow(/50/);
    expect(db.asked).toHaveLength(0);
  });
});
